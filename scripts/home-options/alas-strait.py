"""
Chart data for homepage option B (the Alas Strait chart).

Source: Natural Earth 1:10m land (ne_10m_land.geojson, public domain,
https://www.naturalearthdata.com/). Download it, then run:

    python scripts/home-options/alas-strait.py path/to/ne_10m_land.geojson

Writes src/components/home-options/b/alasStrait.ts: the coast of Lombok and West
Sumbawa clipped to the chart, smoothed (Catmull-Rom to cubic Beziers), the
positions of the resort and the two ferry ports, and graticule ticks.
"""
import json
import math
import sys
from pathlib import Path

W, H = 1600, 900
LON0, LON1 = 116.40, 117.12
LAT_C = -8.62

KX = math.cos(math.radians(LAT_C))
SCALE = W / ((LON1 - LON0) * KX)
LAT_TOP = LAT_C + (H / SCALE) / 2
LAT_BOTTOM = LAT_TOP - H / SCALE


def project(lon, lat):
    return ((lon - LON0) * KX * SCALE, (LAT_TOP - lat) * SCALE)


def unproject_lat(y):
    return LAT_TOP - y / SCALE


# Resort: coordinates of the Google Maps pin used on the site (contact.mapEmbedUrl).
# Ports: approximate, snapped to the nearest coast vertex below.
PLACES = {
    "mocean": (116.7670, -8.6741),
    "potoTano": (116.8227, -8.5504),
    "kayangan": (116.6735, -8.4985),
}
SWQ = (117.4122, -8.4890)  # Sumbawa Besar airport, off the east edge


def smooth_path(pts):
    """Closed Catmull-Rom spline through pts, as SVG cubic Beziers."""
    n = len(pts)
    d = [f"M{pts[0][0]:.1f},{pts[0][1]:.1f}"]
    for i in range(n):
        p0 = pts[(i - 1) % n]
        p1 = pts[i]
        p2 = pts[(i + 1) % n]
        p3 = pts[(i + 2) % n]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d.append(f"C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}")
    return "".join(d) + "Z"


def main(src, out):
    data = json.loads(Path(src).read_text())
    ex = 0.15
    bb = (LON0 - ex, LON1 + ex, LAT_BOTTOM - ex, LAT_TOP + ex)
    rings = []
    for feature in data["features"]:
        geom = feature["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            for ring in poly:
                xs = [p[0] for p in ring]
                ys = [p[1] for p in ring]
                if max(xs) < bb[0] or min(xs) > bb[1] or max(ys) < bb[2] or min(ys) > bb[3]:
                    continue
                pts, last = [], None
                for x, y in ring[:-1]:
                    x = min(max(x, bb[0]), bb[1])
                    y = min(max(y, bb[2]), bb[3])
                    p = project(x, y)
                    k = (round(p[0], 1), round(p[1], 1))
                    if k != last:
                        pts.append(k)
                        last = k
                if len(pts) > 2:
                    rings.append(pts)

    # Coast vertices actually inside the chart, for snapping the ports.
    inside = [p for ring in rings for p in ring if 0 < p[0] < W and 0 < p[1] < H]

    def snap(p):
        return min(inside, key=lambda q: (q[0] - p[0]) ** 2 + (q[1] - p[1]) ** 2)

    places = {}
    for key, (lon, lat) in PLACES.items():
        p = project(lon, lat)
        if key != "mocean":
            p = snap(p)
        places[key] = [round(p[0], 1), round(p[1], 1)]
    swq = project(*SWQ)

    def fmt_lon(v):
        deg = int(v)
        minutes = round((v - deg) * 60)
        return f"{deg}°{minutes:02d}′E" if minutes else f"{deg}°E"

    def fmt_lat(v):
        a = abs(v)
        deg = int(a)
        minutes = round((a - deg) * 60)
        return f"{deg}°{minutes:02d}′S" if minutes else f"{deg}°S"

    lon_ticks = []
    m = math.ceil(LON0 * 60 / 5) * 5
    while m / 60 <= LON1:
        x = project(m / 60, LAT_C)[0]
        lon_ticks.append({"x": round(x, 1), **({"label": fmt_lon(m / 60)} if m % 10 == 0 else {})})
        m += 5
    lat_ticks = []
    m = math.floor(LAT_TOP * 60 / 5) * 5
    while m / 60 >= LAT_BOTTOM:
        y = project(LON0, m / 60)[1]
        lat_ticks.append({"y": round(y, 1), **({"label": fmt_lat(m / 60)} if m % 10 == 0 else {})})
        m -= 5

    ts = [
        "/**",
        " * Chart data for homepage option B. Generated by scripts/home-options/alas-strait.py",
        " * from Natural Earth 1:10m land (public domain). Do not edit by hand.",
        f" * Projection: equirectangular at {LAT_C}°, lon {LON0} to {LON1}, viewBox {W}x{H}.",
        " */",
        f"export const chartSize = {{ width: {W}, height: {H} }} as const;",
        "",
        "/** Land outlines (Lombok, Sumbawa and the islands in view). */",
        "export const land: readonly string[] = " + json.dumps([smooth_path(r) for r in rings], indent=2) + ";",
        "",
        "/** Positions in chart units. The ports are snapped to the coast. */",
        "export const places = " + json.dumps(places) + " as const;",
        "",
        "/** Sumbawa Besar airport (SWQ), east of the chart edge. */",
        f"export const swq = {{ x: {swq[0]:.1f}, y: {swq[1]:.1f} }} as const;",
        "",
        "/** Border bars (one per minute of arc) and the kilometre scale. */",
        "export const scale = " + json.dumps({
            "lonMinuteStart": round(project(math.ceil(LON0 * 60) / 60, LAT_C)[0], 2),
            "pxPerMinuteLon": round(KX * SCALE / 60, 3),
            "latMinuteStart": round(project(LON0, math.floor(LAT_TOP * 60) / 60)[1], 2),
            "pxPerMinuteLat": round(SCALE / 60, 3),
            "pxPerKm": round(SCALE / 111.32, 3),
        }) + " as const;",
        "",
        "/** Graticule ticks every 5 minutes, labelled every 10. */",
        "export const lonTicks: readonly { x: number; label?: string }[] = " + json.dumps(lon_ticks) + ";",
        "export const latTicks: readonly { y: number; label?: string }[] = " + json.dumps(lat_ticks) + ";",
        "",
    ]
    Path(out).write_text("\n".join(ts), encoding="utf-8", newline="\n")
    print(len(rings), "rings;", places, "swq", swq, "lat", LAT_TOP, LAT_BOTTOM)


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[2]
    main(sys.argv[1], root / "src/components/home-options/b/alasStrait.ts")
